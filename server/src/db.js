import { connect, db, driver } from './pg.js';

export { db };

/**
 * O esquema, em Postgres. Era SQLite num arquivo ao lado do processo, e a
 * traducao guardou duas escolhas de proposito:
 *
 * 1. Datas continuam sendo texto "AAAA-MM-DD HH:MM:SS" em UTC, e nao
 *    timestamptz. O app inteiro -- servidor, front e o backup em JSON -- ja
 *    troca datas nesse formato, e a funcao datetime() abaixo mantem o SQL
 *    identico ao que era. Trocar o tipo mudaria o formato em toda a API sem
 *    ganho nenhum para uma lista de compras.
 * 2. As flags (picked, available, archived, reusable) continuam inteiras 0/1,
 *    do jeito que o SQLite guardava e que o front ja le.
 */
const ESQUEMA = `
-- datetime('now') e datetime('now', '-30 minutes'): existiam no SQLite e sao
-- usadas em trinta lugares. Recriadas aqui, a traducao nao precisou tocar em
-- nenhuma consulta -- e o formato da data continua o mesmo em toda a API.
CREATE OR REPLACE FUNCTION datetime(quando text) RETURNS text AS $$
  SELECT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS')
$$ LANGUAGE sql STABLE;

CREATE OR REPLACE FUNCTION datetime(quando text, modificador text) RETURNS text AS $$
  SELECT to_char(
    (now() AT TIME ZONE 'utc') +
    (CASE WHEN left(modificador, 1) IN ('-', '+') THEN modificador ELSE '+' || modificador END)::interval,
    'YYYY-MM-DD HH24:MI:SS')
$$ LANGUAGE sql STABLE;

CREATE TABLE IF NOT EXISTS households (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT datetime('now')
);

CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id  INTEGER NOT NULL REFERENCES households(id) ON DELETE CASCADE,
  name          TEXT NOT NULL,
  email         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  color         TEXT NOT NULL DEFAULT '#0ea5e9',
  created_at    TEXT NOT NULL DEFAULT datetime('now')
);

CREATE TABLE IF NOT EXISTS sessions (
  token      TEXT PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL DEFAULT datetime('now'),
  expires_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id);

-- ---------------------------------------------------------------- catalogo
-- O catalogo e cache dos mercados: se apagar, ele se refaz na proxima busca.
-- Produtos com EAN sao unificados por EAN; sem EAN, por nome normalizado.
CREATE TABLE IF NOT EXISTS products (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ean             TEXT UNIQUE,
  match_key       TEXT NOT NULL UNIQUE,
  name            TEXT NOT NULL,
  brand           TEXT,
  category        TEXT NOT NULL DEFAULT 'outros',
  image_url       TEXT,
  unit            TEXT NOT NULL DEFAULT 'un',
  category_locked INTEGER NOT NULL DEFAULT 0,
  subcategory     TEXT,
  size_label      TEXT,
  size_value      DOUBLE PRECISION,
  size_kind       TEXT,
  created_at      TEXT NOT NULL DEFAULT datetime('now'),
  updated_at      TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category);
CREATE INDEX IF NOT EXISTS idx_products_name ON products(name);
CREATE INDEX IF NOT EXISTS idx_products_sub ON products(category, subcategory);

CREATE TABLE IF NOT EXISTS offers (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id   INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  market       TEXT NOT NULL,
  market_sku   TEXT NOT NULL,
  name         TEXT NOT NULL,
  price        DOUBLE PRECISION,
  list_price   DOUBLE PRECISION,
  available    INTEGER NOT NULL DEFAULT 1,
  url          TEXT,
  image_url    TEXT,
  category     TEXT,
  updated_at   TEXT NOT NULL DEFAULT datetime('now'),
  UNIQUE(market, market_sku)
);
CREATE INDEX IF NOT EXISTS idx_offers_product ON offers(product_id);
CREATE INDEX IF NOT EXISTS idx_offers_market ON offers(market);

-- Cache das buscas por termo, para nao bater nos sites a cada tecla.
CREATE TABLE IF NOT EXISTS search_cache (
  market      TEXT NOT NULL,
  term        TEXT NOT NULL,
  product_ids TEXT NOT NULL,
  fetched_at  TEXT NOT NULL DEFAULT datetime('now'),
  PRIMARY KEY (market, term)
);

-- ------------------------------------------------------------------ listas
-- Toda lista e preparacao: e nela que se anota o que precisa comprar.
-- kind: 'general' -> a lista geral, uma por casa, para a proxima compra
--       'quick'   -> lista nomeada (limpeza, churrasco, o que faltou...)
-- reusable: lista rapida cadastrada continua existindo depois de usada; a
-- lista geral e as de sobra sao de uso unico e o carrinho as consome.
CREATE TABLE IF NOT EXISTS lists (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id INTEGER NOT NULL REFERENCES households(id) ON DELETE CASCADE,
  name         TEXT NOT NULL,
  kind         TEXT NOT NULL DEFAULT 'quick',
  reusable     INTEGER NOT NULL DEFAULT 1,
  emoji        TEXT NOT NULL DEFAULT '🛒',
  archived     INTEGER NOT NULL DEFAULT 0,
  created_by   INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at   TEXT NOT NULL DEFAULT datetime('now'),
  updated_at   TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_lists_household ON lists(household_id, kind);

CREATE TABLE IF NOT EXISTS list_items (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  list_id        INTEGER NOT NULL REFERENCES lists(id) ON DELETE CASCADE,
  product_id     INTEGER REFERENCES products(id) ON DELETE SET NULL,
  name           TEXT NOT NULL,
  qty            DOUBLE PRECISION NOT NULL DEFAULT 1,
  unit           TEXT NOT NULL DEFAULT 'un',
  category       TEXT NOT NULL DEFAULT 'outros',
  image_url      TEXT,
  note           TEXT,
  position       DOUBLE PRECISION NOT NULL DEFAULT 0,
  added_by       INTEGER REFERENCES users(id) ON DELETE SET NULL,
  -- Preco de cada mercado no momento em que o item entrou na lista. E este o
  -- numero que vale no mercado: quem esta com o carrinho na mao nao quer que o
  -- app saia consultando preco novo -- a decisao de onde comprar ja foi tomada.
  price_snapshot TEXT,
  snapshot_at    TEXT,
  -- Mercado escolhido para este item; vazio = onde estiver mais barato.
  market         TEXT,
  created_at     TEXT NOT NULL DEFAULT datetime('now'),
  updated_at     TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_list_items_list ON list_items(list_id);

-- ------------------------------------------------------------------ compras
-- Uma "trip" e uma ida ao mercado: nasce de uma ou mais listas, e durante ela
-- se marca o que ja foi pego e se anota o preco real.
CREATE TABLE IF NOT EXISTS trips (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  household_id INTEGER NOT NULL REFERENCES households(id) ON DELETE CASCADE,
  list_id      INTEGER REFERENCES lists(id) ON DELETE SET NULL,
  list_name    TEXT NOT NULL DEFAULT 'Compra',
  market       TEXT,
  status       TEXT NOT NULL DEFAULT 'active',
  started_by   INTEGER REFERENCES users(id) ON DELETE SET NULL,
  started_at   TEXT NOT NULL DEFAULT datetime('now'),
  finished_at  TEXT
);
CREATE INDEX IF NOT EXISTS idx_trips_household ON trips(household_id, status);

CREATE TABLE IF NOT EXISTS trip_items (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id        INTEGER NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
  list_item_id   INTEGER REFERENCES list_items(id) ON DELETE SET NULL,
  product_id     INTEGER REFERENCES products(id) ON DELETE SET NULL,
  name           TEXT NOT NULL,
  qty            DOUBLE PRECISION NOT NULL DEFAULT 1,
  unit           TEXT NOT NULL DEFAULT 'un',
  category       TEXT NOT NULL DEFAULT 'outros',
  image_url      TEXT,
  note           TEXT,
  picked         INTEGER NOT NULL DEFAULT 0,
  unit_price     DOUBLE PRECISION,
  picked_qty     DOUBLE PRECISION,
  picked_by      INTEGER REFERENCES users(id) ON DELETE SET NULL,
  picked_at      TEXT,
  expected       DOUBLE PRECISION,
  source_list_id INTEGER,
  market         TEXT,
  price_snapshot TEXT,
  swapped_from   TEXT
);
CREATE INDEX IF NOT EXISTS idx_trip_items_trip ON trip_items(trip_id);

-- Um carrinho e montado de uma ou mais listas, e guarda de quais veio: no
-- fecho e isso que diz o que consumir e o que deixar cadastrado.
-- Sem chave primaria em (trip_id, list_id) de proposito: a lista pode ser
-- apagada depois (ON DELETE SET NULL) e a linha precisa sobreviver com o nome,
-- para o historico continuar dizendo de onde a compra saiu.
CREATE TABLE IF NOT EXISTS trip_lists (
  trip_id   INTEGER NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
  list_id   INTEGER REFERENCES lists(id) ON DELETE SET NULL,
  list_name TEXT NOT NULL,
  kind      TEXT NOT NULL DEFAULT 'quick',
  reusable  INTEGER NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_trip_lists_par ON trip_lists(trip_id, list_id);

-- Amarra cada item do carrinho aos itens de lista que o originaram -- plural,
-- porque o mesmo produto pode vir de duas listas e virar uma linha so. Sem
-- esse rastro, o fecho nao sabe o que saiu de onde.
CREATE TABLE IF NOT EXISTS trip_item_sources (
  trip_item_id INTEGER NOT NULL REFERENCES trip_items(id) ON DELETE CASCADE,
  list_item_id INTEGER NOT NULL,
  list_id      INTEGER,
  PRIMARY KEY (trip_item_id, list_item_id)
);
CREATE INDEX IF NOT EXISTS idx_trip_item_sources_item ON trip_item_sources(trip_item_id);

-- Historico de precos pagos de verdade, alimentado ao fechar cada compra.
CREATE TABLE IF NOT EXISTS price_history (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id  INTEGER REFERENCES products(id) ON DELETE CASCADE,
  match_key   TEXT NOT NULL,
  name        TEXT NOT NULL,
  market      TEXT,
  unit_price  DOUBLE PRECISION NOT NULL,
  trip_id     INTEGER REFERENCES trips(id) ON DELETE SET NULL,
  recorded_at TEXT NOT NULL DEFAULT datetime('now')
);
CREATE INDEX IF NOT EXISTS idx_price_history_key ON price_history(match_key, recorded_at);

-- Chave/valor para controle interno (versao do classificador, capa do
-- corredor escolhida a mao).
CREATE TABLE IF NOT EXISTS meta (
  key   TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- RLS ligado em tudo, sem nenhuma policy. Isso nao afeta este servidor -- ele
-- conecta como dono das tabelas, e dono passa por cima de RLS -- e fecha a
-- porta que o Supabase deixa aberta: no projeto dele, tabela em "public" fica
-- ao alcance da API publica (a anon key vai no navegador de qualquer um). Sem
-- policy, essa API nao le nem escreve uma linha. E aqui tem e-mail e hash de
-- senha.
DO $bloco$
DECLARE tabela text;
BEGIN
  FOREACH tabela IN ARRAY ARRAY[
    'households', 'users', 'sessions', 'products', 'offers', 'search_cache',
    'lists', 'list_items', 'trips', 'trip_items', 'trip_lists',
    'trip_item_sources', 'price_history', 'meta'
  ] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', tabela);
  END LOOP;
END
$bloco$;
`;

// Nomes antigos, de quando o "carrinho" era uma lista -- antes de o carrinho
// passar a ser a ida ao mercado montada a partir de uma ou mais listas.
const REMENDOS = `
  UPDATE lists SET kind = 'general', reusable = 0 WHERE kind = 'cart';
  UPDATE lists SET kind = 'quick'                 WHERE kind = 'template';
  UPDATE lists SET reusable = 0 WHERE kind = 'general';
  UPDATE lists SET name = 'Lista geral', emoji = '📝' WHERE kind = 'general' AND name = 'Carrinho';
`;

let pronto = null;

/** Abre a conexao e garante o esquema. Roda uma vez, no boot. */
export async function migrate() {
  if (!pronto) {
    pronto = (async () => {
      await connect();
      await db.exec(ESQUEMA);
      await db.exec(REMENDOS);
      return driver();
    })();
  }
  return pronto;
}

export async function metaGet(key) {
  const row = await db.prepare('SELECT value FROM meta WHERE key = ?').get(key);
  return row?.value ?? null;
}

export async function metaSet(key, value) {
  await db
    .prepare('INSERT INTO meta (key, value) VALUES (?, ?) ON CONFLICT (key) DO UPDATE SET value = excluded.value')
    .run(key, String(value));
}

export function nowIso() {
  return new Date().toISOString().replace('T', ' ').slice(0, 19);
}
